package models

import (
	"encoding/json"
	"time"

	"github.com/google/uuid"
)

// ZoneStatus represents the current operational status of a code zone.
type ZoneStatus string

const (
	ZoneStatusActive   ZoneStatus = "active"
	ZoneStatusFrozen   ZoneStatus = "frozen"
	ZoneStatusThawing  ZoneStatus = "thawing"
)

// ChangeClassification represents the impact level of an external change.
type ChangeClassification string

const (
	ChangeClassificationMinor    ChangeClassification = "minor"
	ChangeClassificationModerate ChangeClassification = "moderate"
	ChangeClassificationMajor    ChangeClassification = "major"
)

// SubmissionStatus represents the lifecycle state of a codex submission.
type SubmissionStatus string

const (
	SubmissionStatusPending       SubmissionStatus = "pending"
	SubmissionStatusSubmitted     SubmissionStatus = "submitted"
	SubmissionStatusAutoGenerated SubmissionStatus = "auto_generated"
	SubmissionStatusReviewed      SubmissionStatus = "reviewed"
)

// CodeZone represents a logical grouping of code paths that can be frozen or thawed.
type CodeZone struct {
	ID           uuid.UUID  `json:"id" db:"id"`
	Name         string     `json:"name" db:"name"`
	ModulePaths  []string   `json:"module_paths" db:"module_paths"`
	Status       ZoneStatus `json:"status" db:"status"`
	FrozenReason *string    `json:"frozen_reason,omitempty" db:"frozen_reason"`
	FrozenAt     *time.Time `json:"frozen_at,omitempty" db:"frozen_at"`
}

// ExternalChange represents a change detected from outside the autonomous pipeline (e.g., a human PR).
type ExternalChange struct {
	ID               uuid.UUID            `json:"id" db:"id"`
	PRURL            string               `json:"pr_url" db:"pr_url"`
	Classification   ChangeClassification `json:"classification" db:"classification"`
	AffectedZones    []string             `json:"affected_zones" db:"affected_zones"`
	SubmissionStatus SubmissionStatus     `json:"submission_status" db:"submission_status"`
	DetectedAt       *time.Time           `json:"detected_at,omitempty" db:"detected_at"`
	SubmittedAt      *time.Time           `json:"submitted_at,omitempty" db:"submitted_at"`
}

// CodexSubmission records the answers submitted for a codex update triggered by an external change.
type CodexSubmission struct {
	ID               uuid.UUID       `json:"id" db:"id"`
	ExternalChangeID uuid.UUID       `json:"external_change_id" db:"external_change_id"`
	Answers          json.RawMessage `json:"answers" db:"answers"`
	SubmittedBy      string          `json:"submitted_by" db:"submitted_by"`
	SubmittedAt      time.Time       `json:"submitted_at" db:"submitted_at"`
}
