#!/usr/bin/env python3
"""Generate and check THIRD_PARTY_NOTICES.md.

    python scripts/third_party_notices.py --check   # exit 1 if stale, a license is not allowed, or a text is missing
    python scripts/third_party_notices.py --write   # regenerate THIRD_PARTY_NOTICES.md

Inputs (committed):
  third_party/go-licenses.csv            output of `go-licenses report ./...` without this module's rows
  third_party/npm-dashboard.json         output of `license-checker --production --json --excludePrivatePackages`
  third_party/npm-portal.json            same, for portal/
  third_party/licenses/                  one license text per component (see text_path);
                                         refresh with scripts/collect_license_texts.py
Local paths in the npm reports are never rendered.

The benchmark corpus ships no upstream code: each task names its upstream
repository and commits, and the verifier fetches them at run time.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEXTS = ROOT / "third_party" / "licenses"

ALLOWED = {"Apache-2.0", "MIT", "BSD-2-Clause", "BSD-3-Clause", "ISC", "MPL-2.0", "0BSD", "Unlicense", "CC0-1.0"}


def _expr_allowed(expr: str) -> bool:
    """An SPDX expression is allowed when every alternative of an OR, or every term of an AND, is allowed."""
    e = expr.strip().strip("()")
    if " OR " in e:
        return any(_expr_allowed(p) for p in e.split(" OR "))
    if " AND " in e:
        return all(_expr_allowed(p) for p in e.split(" AND "))
    return e in ALLOWED


def _safe(name: str) -> str:
    return name.replace("/", "__").replace("@", "_").replace(":", "_")


def text_path(kind: str, name: str) -> str:
    """Relative path, under third_party/licenses/, of a component's license text.

    kind is "go" (module path) or "npm" (name@version).
    """
    return f"{kind}/{_safe(name)}.txt"


def _read(root: Path):
    with (root / "third_party" / "go-licenses.csv").open(encoding="utf-8", newline="") as f:
        go = [r for r in csv.reader(f) if r]
    npm = {}
    for name in ("dashboard", "portal"):
        npm[name] = json.loads((root / "third_party" / f"npm-{name}.json").read_text(encoding="utf-8"))
    return go, npm


def components(root: Path = ROOT) -> list[tuple[str, str]]:
    """Every (kind, name) that needs a license text."""
    go, npm = _read(root)
    out = [("go", mod) for mod, _u, _s in go]
    for data in npm.values():
        out += [("npm", pkg) for pkg in data]
    return sorted(set(out))


def problems(root: Path = ROOT, texts_dir: Path | None = None) -> list[str]:
    go, npm = _read(root)
    texts = texts_dir or root / "third_party" / "licenses"
    out: list[str] = []
    for kind, name in components(root):
        rel = text_path(kind, name)
        f = texts / rel
        if not f.exists() or not f.read_text(encoding="utf-8", errors="replace").strip():
            out.append(f"{name}: no license text at third_party/licenses/{rel}")
    for mod, _url, spdx in go:
        if not _expr_allowed(spdx):
            out.append(f"Go module {mod}: license {spdx} is not allowed")
    for name, data in npm.items():
        for pkg, info in data.items():
            spdx = str(info.get("licenses", ""))
            if not _expr_allowed(spdx):
                out.append(f"npm ({name}) {pkg}: license {spdx} is not allowed")
    return out


def render(root: Path = ROOT) -> str:
    go, npm = _read(root)
    lines = [
        "# Third-party notices",
        "",
        "Autonomous Engine is licensed under the Apache License, Version 2.0 (see `LICENSE` and `NOTICE`).",
        "It depends on the third-party packages listed below, each under its own license.",
        "The full license text and any NOTICE file of every component are in `third_party/licenses/`.",
        "This file is generated by `scripts/third_party_notices.py`; do not edit it by hand.",
        "",
        "The benchmark corpus in `benchmarks/` contains no third-party code. Each task names an upstream",
        "repository and commit, which the benchmark tools fetch at run time under that project's license.",
        "",
        "## Go modules",
        "",
        "| Module | License |",
        "|---|---|",
    ]
    for mod, _url, spdx in sorted(go):
        lines.append(f"| `{mod}` | {spdx} |")
    for name in ("dashboard", "portal"):
        lines += ["", f"## npm packages ({name}, production)", "", "| Package | License | Repository |", "|---|---|---|"]
        for pkg in sorted(npm[name]):
            info = npm[name][pkg]
            lines.append(f"| `{pkg}` | {info.get('licenses', '')} | {info.get('repository', '')} |")
    return "\n".join(lines) + "\n"


def check(root: Path = ROOT) -> int:
    ps = problems(root)
    for p in ps:
        print(p, file=sys.stderr)
    target = root / "THIRD_PARTY_NOTICES.md"
    if not target.exists() or target.read_text(encoding="utf-8").replace("\r\n", "\n") != render(root):
        print("THIRD_PARTY_NOTICES.md is stale; run scripts/third_party_notices.py --write", file=sys.stderr)
        return 1
    return 1 if ps else 0


def write(root: Path = ROOT) -> None:
    (root / "THIRD_PARTY_NOTICES.md").write_text(render(root), encoding="utf-8", newline="\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    a = ap.parse_args()
    if a.write:
        write()
        return 0
    return check()


if __name__ == "__main__":
    sys.exit(main())
